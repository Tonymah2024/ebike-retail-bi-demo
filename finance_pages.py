@st.cache_data
def t(name, **kw):
    p = TABLES / f"fin_{name}.csv"
    return pd.read_csv(p, **kw) if p.exists() else pd.DataFrame()


def stmt(name):
    d = t(name, index_col=0)
    return d.drop(columns=[c for c in ("data_status", "label") if c in d.columns]), d.get("label")


@st.cache_data
def fbase():
    js = json.loads((TABLES / "fin_forecast_base.json").read_text())
    dv = pd.DataFrame(js["drivers"]).T
    dv.columns = range(1, F.H + 1)
    return {"A": js["A"], "drivers": dv, "opening": js["opening"]}


def acct(v, d=0):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return ""
    return f"({abs(v):,.{d}f})" if v < -0.5 * 10 ** -d else f"{v:,.{d}f}"


def money(v):
    s = "-" if v < 0 else ""
    v = abs(v)
    return f"{s}${v / 1e6:,.2f}M" if v >= 1e6 else f"{s}${v:,.0f}"


def fmt_table(df, labels=None, pct_rows=()):
    x = df.copy()
    if labels is not None:
        x.index = [labels.get(k, k) for k in x.index]
    out = pd.DataFrame({c: [f"{v:.1f}%" if i in pct_rows else acct(v) for i, v in zip(x.index, x[c])] for c in x.columns}, index=x.index)
    out.index.name = "CAD"
    return out


def kpis(items):
    cols = st.columns(len(items))
    for c, (label, value, delta, good) in zip(cols, items):
        color = BRAND["good"] if good is True else (BRAND["bad"] if good is False else BRAND["muted"])
        c.markdown(f"<div class='kpi'><div class='l'>{label}</div><div class='v'>{value}</div><div class='d' style='color:{color}'>{delta or '&nbsp;'}</div></div>",
                   unsafe_allow_html=True)


def show(fig, h=400):
    fig.update_layout(height=h, **PLOT)
    st.plotly_chart(fig, use_container_width=True)


def dl_csv(df, name, label="Download CSV"):
    st.download_button(label, df.to_csv().encode(), file_name=f"{name}.csv", mime="text/csv", key=f"fdl_{name}")


def dl_file(path: Path, label):
    if path.exists():
        mime = "application/pdf" if path.suffix == ".pdf" else "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
        st.download_button(label, path.read_bytes(), file_name=path.name, mime=mime, key=f"ff_{path.name}")


def banner(forecast=False):
    msg = "FORECAST - projections, not historical fact. " if forecast else ""
    st.markdown(f"<div class='vv-synth' style='margin:4px 0 10px'>⚠ {msg}{P.FIN_LABEL}.</div>", unsafe_allow_html=True)


def waterfall(labels, values, measures, title):
    fig = go.Figure(go.Waterfall(x=labels, y=values, measure=measures, text=[acct(v / 1000, 1) + "K" for v in values], textposition="outside",
                                 increasing=dict(marker_color=UP), decreasing=dict(marker_color=DOWN), totals=dict(marker_color=TOT),
                                 connector=dict(line=dict(color="#bbb", width=1))))
    fig.update_layout(title=title, yaxis_tickprefix="$", showlegend=False)
    return fig


